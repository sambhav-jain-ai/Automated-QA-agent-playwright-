"""Crawler engine that launches a real Playwright browser for automation.

When Playwright is installed, this module launches a visible browser (headless=False)
to navigate to the target site, fill credentials, handle OTP, and crawl the page.
If Playwright is not available, it falls back to simulation mode while still
generating runnable Playwright scripts.
"""

import os
import textwrap
import time
from dataclasses import dataclass, field
from typing import Callable, Optional

# Try to import Playwright - use real browser if available
try:
    from playwright.sync_api import sync_playwright, Page, Browser
    PLAYWRIGHT_AVAILABLE = True
except ImportError:
    PLAYWRIGHT_AVAILABLE = False


@dataclass
class CrawlerResult:
    """Result from a crawler run."""
    visited_urls: list[str] = field(default_factory=list)
    discovered_buttons: list[str] = field(default_factory=list)
    generated_test_cases: list[dict] = field(default_factory=list)
    screenshots: list[str] = field(default_factory=list)
    playwright_script_path: str = ""


class CrawlerEngine:
    """Engine that launches a real Playwright browser (headless=False) for crawling.

    When Playwright is installed, the engine opens a visible browser window,
    navigates to the login page, fills credentials, clicks login, and waits
    for OTP if needed. The OTP is generated by the TARGET application (not by
    this tool) - we wait for the user to receive it and enter it in our UI.

    If Playwright is not installed, falls back to simulation mode.
    """

    def __init__(self, output_dir: str = "/projects/sandbox/playwright-autotest/generated_scripts"):
        self.output_dir = output_dir
        self.screenshots_dir = os.path.join(
            os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
            "screenshots"
        )

    def run(
        self,
        frontend_url: str,
        username: str,
        password: str,
        otp_provider_fn: Optional[Callable[[], str]] = None,
        session_log_fn: Optional[Callable[[str], None]] = None,
        session_id: str = "default",
    ) -> CrawlerResult:
        """Run the crawler and generate a Playwright script.

        If Playwright is installed, launches a real visible browser (headless=False).
        Otherwise, falls back to simulation mode.

        Args:
            frontend_url: URL of the frontend application to crawl
            username: Login username
            password: Login password
            otp_provider_fn: Function that blocks until OTP is available, returns OTP string
            session_log_fn: Callback for logging progress messages
            session_id: Unique session identifier

        Returns:
            CrawlerResult with crawl results and generated script path
        """
        def log(msg: str) -> None:
            if session_log_fn:
                session_log_fn(msg)

        log("[Phase 1 - UI Crawl] Starting browser automation...")
        log(f"[Phase 1] Target: {frontend_url}")

        # Generate the Playwright script (always, for download)
        script_content = self._generate_crawl_script(
            frontend_url, username, password, session_id
        )

        # Save script
        os.makedirs(self.output_dir, exist_ok=True)
        script_path = os.path.join(self.output_dir, f"crawl_{session_id}.py")
        with open(script_path, "w") as f:
            f.write(script_content)

        log(f"[Phase 1] Generated Playwright script: {script_path}")

        # Use real Playwright browser if available
        if PLAYWRIGHT_AVAILABLE:
            log("[Phase 1] Playwright detected - launching real browser (headless=False)...")
            return self._run_real_browser(
                frontend_url=frontend_url,
                username=username,
                password=password,
                otp_provider_fn=otp_provider_fn,
                log=log,
                session_id=session_id,
                script_path=script_path,
            )
        else:
            log("[Phase 1] Playwright not installed - running in simulation mode")
            log("[Phase 1] Install playwright for real browser: pip install playwright && python -m playwright install chromium")
            return self._run_simulation(
                frontend_url=frontend_url,
                username=username,
                password=password,
                otp_provider_fn=otp_provider_fn,
                log=log,
                session_id=session_id,
                script_path=script_path,
            )

    def _run_real_browser(
        self,
        frontend_url: str,
        username: str,
        password: str,
        otp_provider_fn: Optional[Callable[[], str]],
        log: Callable[[str], None],
        session_id: str,
        script_path: str,
    ) -> CrawlerResult:
        """Launch a real Playwright browser with headless=False and perform the crawl.

        The browser is visible so the target application can generate OTP via its
        own mechanisms (SMS, email, authenticator app, etc.).
        """
        os.makedirs(self.screenshots_dir, exist_ok=True)
        visited_urls: list[str] = []
        discovered_buttons: list[str] = []
        screenshots: list[str] = []

        with sync_playwright() as p:
            # Launch visible browser (headless=False) so OTP gets generated
            log("[Phase 1] Launching Chromium browser (headless=False)...")
            browser = p.chromium.launch(headless=False)
            context = browser.new_context(
                viewport={"width": 1280, "height": 720}
            )
            page = context.new_page()

            try:
                # Step 1: Navigate to the login page
                log(f"[Phase 1] Navigating to login page: {frontend_url}")
                page.goto(frontend_url, wait_until="domcontentloaded", timeout=30000)
                visited_urls.append(frontend_url)

                # Step 2: Wait 5 seconds on the login page
                log("[Phase 1] Waiting 5 seconds on login page...")
                page.wait_for_timeout(5000)

                # Take screenshot of login page
                screenshot_path = os.path.join(self.screenshots_dir, f"{session_id}_01_login.png")
                page.screenshot(path=screenshot_path)
                screenshots.append(screenshot_path)
                log("[Phase 1] Screenshot captured: login page")

                # Step 3: Fill in the username credential
                log(f"[Phase 1] Filling username: {username}")
                username_filled = False
                username_selectors = [
                    'input[name="username"]',
                    'input[name="email"]',
                    'input[type="email"]',
                    'input[name="user"]',
                    'input[name="login"]',
                    '#username',
                    '#email',
                    '#login',
                    'input[placeholder*="user" i]',
                    'input[placeholder*="email" i]',
                ]
                for selector in username_selectors:
                    try:
                        elem = page.query_selector(selector)
                        if elem and elem.is_visible():
                            elem.fill(username)
                            username_filled = True
                            log(f"[Phase 1] Username filled using selector: {selector}")
                            break
                    except Exception:
                        continue

                if not username_filled:
                    # Try the first visible text/email input
                    try:
                        inputs = page.query_selector_all('input[type="text"], input[type="email"], input:not([type])')
                        for inp in inputs:
                            if inp.is_visible():
                                inp.fill(username)
                                username_filled = True
                                log("[Phase 1] Username filled using first visible text input")
                                break
                    except Exception:
                        pass

                # Step 4: Fill in the password credential
                log("[Phase 1] Filling password: ********")
                password_filled = False
                password_selectors = [
                    'input[name="password"]',
                    'input[type="password"]',
                    '#password',
                    'input[name="pass"]',
                ]
                for selector in password_selectors:
                    try:
                        elem = page.query_selector(selector)
                        if elem and elem.is_visible():
                            elem.fill(password)
                            password_filled = True
                            log(f"[Phase 1] Password filled using selector: {selector}")
                            break
                    except Exception:
                        continue

                # Step 5: Click the login button
                log("[Phase 1] Clicking login button...")
                login_clicked = False
                login_selectors = [
                    'button[type="submit"]',
                    'input[type="submit"]',
                    'button:has-text("Login")',
                    'button:has-text("Sign in")',
                    'button:has-text("Log in")',
                    'button:has-text("Submit")',
                    '#loginBtn',
                    '#submitBtn',
                    '.login-btn',
                    '.submit-btn',
                ]
                for selector in login_selectors:
                    try:
                        elem = page.query_selector(selector)
                        if elem and elem.is_visible():
                            elem.click()
                            login_clicked = True
                            log(f"[Phase 1] Login button clicked using selector: {selector}")
                            break
                    except Exception:
                        continue

                if not login_clicked:
                    log("[Phase 1] Warning: Could not find login button, trying Enter key")
                    try:
                        page.keyboard.press("Enter")
                    except Exception:
                        pass

                log("[Phase 1] Login credentials submitted successfully")

                # Step 6: Wait for page to respond after login (30s to avoid 429 rate limiting)
                log("[Phase 1] Waiting 30 seconds for page response after login...")
                page.wait_for_timeout(30000)

                # Take screenshot after login attempt
                screenshot_path = os.path.join(self.screenshots_dir, f"{session_id}_02_after_login.png")
                page.screenshot(path=screenshot_path)
                screenshots.append(screenshot_path)

                # Track the current URL after login
                current_url = page.url
                if current_url != frontend_url and current_url not in visited_urls:
                    visited_urls.append(current_url)

                # Step 7: Check if OTP field appears on the page
                log("[Phase 1] Checking for OTP field after login...")
                otp_field = None
                otp_selectors = [
                    'input[name="otp"]',
                    'input[name="code"]',
                    'input[name="verification_code"]',
                    'input[name="verificationCode"]',
                    'input[name="token"]',
                    'input[name="mfa"]',
                    'input[name="2fa"]',
                    'input[placeholder*="OTP" i]',
                    'input[placeholder*="code" i]',
                    'input[placeholder*="verification" i]',
                    '#otp',
                    '#code',
                    '#verificationCode',
                ]
                for selector in otp_selectors:
                    try:
                        elem = page.query_selector(selector)
                        if elem and elem.is_visible():
                            otp_field = elem
                            log(f"[Phase 1] OTP field detected with selector: {selector}")
                            break
                    except Exception:
                        continue

                # If OTP field found, wait for user to enter OTP
                if otp_field and otp_provider_fn:
                    log("[Phase 1] OTP field detected - requesting OTP from user")
                    log("[Phase 1] The target application has generated an OTP (via SMS/email)")
                    log("[OTP] Waiting for OTP input from user...")

                    # Wait for user to provide OTP through our UI
                    otp = otp_provider_fn()

                    if otp:
                        log(f"[Phase 1] OTP received: {'*' * len(otp)}")
                        # Fill OTP in the browser
                        otp_field.fill(otp)
                        log("[Phase 1] OTP entered in browser")

                        # Try to submit OTP
                        otp_submit_selectors = [
                            'button[type="submit"]',
                            'input[type="submit"]',
                            'button:has-text("Verify")',
                            'button:has-text("Submit")',
                            'button:has-text("Confirm")',
                        ]
                        for selector in otp_submit_selectors:
                            try:
                                elem = page.query_selector(selector)
                                if elem and elem.is_visible():
                                    elem.click()
                                    log("[Phase 1] OTP submitted in browser")
                                    break
                            except Exception:
                                continue

                        page.wait_for_timeout(10000)

                        # Screenshot after OTP
                        screenshot_path = os.path.join(self.screenshots_dir, f"{session_id}_03_after_otp.png")
                        page.screenshot(path=screenshot_path)
                        screenshots.append(screenshot_path)

                        current_url = page.url
                        if current_url not in visited_urls:
                            visited_urls.append(current_url)
                elif not otp_field:
                    log("[Phase 1] No OTP field detected - login appears to have succeeded directly")

                # Step 8: Crawl the page after login (discover elements)
                log("[Phase 1] Crawling page after login...")
                current_url = page.url
                if current_url not in visited_urls:
                    visited_urls.append(current_url)

                # Discover all links
                try:
                    links = page.query_selector_all("a[href]")
                    for link in links:
                        href = link.get_attribute("href")
                        if href and not href.startswith("javascript:") and not href.startswith("#"):
                            if href.startswith("/"):
                                # Make relative URL absolute
                                from urllib.parse import urljoin
                                href = urljoin(frontend_url, href)
                            if href not in visited_urls:
                                visited_urls.append(href)
                except Exception as e:
                    log(f"[Phase 1] Warning: Error discovering links: {e}")

                # Discover all buttons
                try:
                    buttons = page.query_selector_all("button, input[type='button'], input[type='submit']")
                    for button in buttons:
                        try:
                            text = button.inner_text() if button.evaluate("el => el.tagName") == "BUTTON" else button.get_attribute("value")
                            if text and text.strip():
                                discovered_buttons.append(text.strip())
                        except Exception:
                            continue
                except Exception as e:
                    log(f"[Phase 1] Warning: Error discovering buttons: {e}")

                # Navigate a few discovered links to expand coverage
                nav_links = page.query_selector_all("nav a[href], .nav a[href], .sidebar a[href], .menu a[href]")
                for i, link in enumerate(nav_links[:5]):
                    try:
                        href = link.get_attribute("href")
                        if href and not href.startswith("javascript:") and not href.startswith("#"):
                            log(f"[Phase 1] Navigating to: {href}")
                            link.click()
                            page.wait_for_timeout(7000)
                            nav_url = page.url
                            if nav_url not in visited_urls:
                                visited_urls.append(nav_url)
                            screenshot_path = os.path.join(
                                self.screenshots_dir, f"{session_id}_{i+4:02d}_nav.png"
                            )
                            page.screenshot(path=screenshot_path)
                            screenshots.append(screenshot_path)
                            page.go_back()
                            page.wait_for_timeout(5000)
                    except Exception as e:
                        log(f"[Phase 1] Warning: Error navigating link: {e}")

                # Final screenshot
                screenshot_path = os.path.join(self.screenshots_dir, f"{session_id}_final.png")
                page.screenshot(path=screenshot_path)
                screenshots.append(screenshot_path)

            except Exception as e:
                log(f"[Phase 1] Browser error: {e}")
                # Take error screenshot if possible
                try:
                    screenshot_path = os.path.join(self.screenshots_dir, f"{session_id}_error.png")
                    page.screenshot(path=screenshot_path)
                    screenshots.append(screenshot_path)
                except Exception:
                    pass
            finally:
                context.close()
                browser.close()
                log("[Phase 1] Browser closed")

        # Generate test cases from discovered elements
        test_cases = self._generate_test_cases(frontend_url, visited_urls, discovered_buttons)

        log(f"[Phase 1] Crawl complete. Found {len(visited_urls)} URLs, {len(discovered_buttons)} buttons")

        return CrawlerResult(
            visited_urls=visited_urls,
            discovered_buttons=discovered_buttons,
            generated_test_cases=test_cases,
            screenshots=screenshots,
            playwright_script_path=script_path,
        )

    def _run_simulation(
        self,
        frontend_url: str,
        username: str,
        password: str,
        otp_provider_fn: Optional[Callable[[], str]],
        log: Callable[[str], None],
        session_id: str,
        script_path: str,
    ) -> CrawlerResult:
        """Fallback simulation mode when Playwright is not installed."""
        # Step 1: Simulate navigating to login page and waiting
        log(f"[Phase 1] Navigating to login page: {frontend_url}")
        log("[Phase 1] Waiting 5 seconds on login page...")
        time.sleep(5)

        # Step 2: Simulate filling and submitting login credentials
        log(f"[Phase 1] Filling username: {username}")
        log("[Phase 1] Filling password: ********")
        log("[Phase 1] Clicking login button...")
        time.sleep(30)
        log("[Phase 1] Login credentials submitted successfully")

        # Simulate discovered elements based on common web app patterns
        visited_urls = [
            frontend_url,
            frontend_url.rstrip("/") + "/login",
            frontend_url.rstrip("/") + "/dashboard",
            frontend_url.rstrip("/") + "/profile",
        ]

        discovered_buttons = [
            "Login Button",
            "Submit Form",
            "Navigation Menu",
            "Logout Button",
            "Dashboard Link",
            "Settings Link",
        ]

        # Step 3: After login, check if OTP is needed
        if otp_provider_fn:
            log("[Phase 1] Checking for OTP field after login...")
            log("[Phase 1] OTP field detected - requesting OTP from user")
            otp = otp_provider_fn()
            log(f"[Phase 1] OTP received: {'*' * len(otp)}")
            visited_urls.append(frontend_url.rstrip("/") + "/otp-verified")

        # Generate test cases from discovered elements
        test_cases = self._generate_test_cases(frontend_url, visited_urls, discovered_buttons)

        log(f"[Phase 1] Crawl complete. Found {len(visited_urls)} URLs, {len(discovered_buttons)} buttons")

        return CrawlerResult(
            visited_urls=visited_urls,
            discovered_buttons=discovered_buttons,
            generated_test_cases=test_cases,
            screenshots=[],
            playwright_script_path=script_path,
        )

    def _generate_test_cases(
        self,
        frontend_url: str,
        visited_urls: list[str],
        discovered_buttons: list[str],
    ) -> list[dict]:
        """Generate test cases from discovered elements."""
        test_cases = [
            {
                "name": "Login flow with valid credentials",
                "steps": ["Navigate to login", "Enter username", "Enter password", "Click login", "Verify dashboard"],
                "expected": "User reaches dashboard",
            },
            {
                "name": "Navigation links are accessible",
                "steps": ["Login", "Click each navigation link", "Verify page loads"],
                "expected": "All navigation links work",
            },
            {
                "name": "Logout functionality",
                "steps": ["Login", "Click logout", "Verify redirect to login"],
                "expected": "User is logged out",
            },
        ]
        return test_cases

    def _generate_crawl_script(
        self,
        frontend_url: str,
        username: str,
        password: str,
        session_id: str,
    ) -> str:
        """Generate a Playwright Python script for crawling the target application."""
        otp_file = f"/tmp/otp_{session_id}.txt"

        script = textwrap.dedent(f'''\
            """Auto-generated Playwright crawl script for session: {session_id}

            Run with: python -m playwright run {session_id}_crawl.py
            Or: python {session_id}_crawl.py (requires playwright installed)
            """

            import asyncio
            import os
            import time
            from playwright.async_api import async_playwright


            async def main():
                async with async_playwright() as p:
                    browser = await p.chromium.launch(headless=False)
                    context = await browser.new_context(
                        viewport={{"width": 1280, "height": 720}},
                        record_video_dir="videos/"
                    )
                    page = await context.new_page()

                    # Navigate to login page
                    print("[Crawl] Navigating to: {frontend_url}")
                    await page.goto("{frontend_url}")
                    await page.wait_for_timeout(5000)  # 5-second wait on login page

                    # Take screenshot of login page
                    await page.screenshot(path="screenshots/01_login_page.png")

                    # Fill credentials
                    print("[Crawl] Filling login credentials...")
                    username_selectors = [
                        'input[name="username"]',
                        'input[name="email"]',
                        'input[type="email"]',
                        '#username',
                        '#email',
                    ]
                    for selector in username_selectors:
                        try:
                            elem = await page.query_selector(selector)
                            if elem:
                                await elem.fill("{username}")
                                break
                        except Exception:
                            continue

                    password_selectors = [
                        'input[name="password"]',
                        'input[type="password"]',
                        '#password',
                    ]
                    for selector in password_selectors:
                        try:
                            elem = await page.query_selector(selector)
                            if elem:
                                await elem.fill("{password}")
                                break
                        except Exception:
                            continue

                    # Click login button
                    login_selectors = [
                        'button[type="submit"]',
                        'input[type="submit"]',
                        'button:has-text("Login")',
                        'button:has-text("Sign in")',
                    ]
                    for selector in login_selectors:
                        try:
                            elem = await page.query_selector(selector)
                            if elem:
                                await elem.click()
                                break
                        except Exception:
                            continue

                    await page.wait_for_timeout(30000)
                    await page.screenshot(path="screenshots/02_after_login.png")

                    # Wait for OTP if needed
                    otp_file = "{otp_file}"
                    print("[Crawl] Checking for OTP requirement...")
                    otp_selectors = [
                        'input[name="otp"]',
                        'input[name="code"]',
                        'input[name="verification_code"]',
                        '#otp',
                    ]
                    otp_field = None
                    for selector in otp_selectors:
                        try:
                            otp_field = await page.query_selector(selector)
                            if otp_field:
                                break
                        except Exception:
                            continue

                    if otp_field:
                        print("[Crawl] OTP field detected. Waiting for OTP...")
                        # Poll for OTP from temp file (written by server)
                        otp_value = ""
                        for _ in range(120):  # Wait up to 2 minutes
                            if os.path.exists(otp_file):
                                with open(otp_file, "r") as f:
                                    otp_value = f.read().strip()
                                if otp_value:
                                    os.remove(otp_file)
                                    break
                            await asyncio.sleep(1)

                        if otp_value:
                            print(f"[Crawl] Entering OTP...")
                            await otp_field.fill(otp_value)
                            # Submit OTP
                            submit = await page.query_selector('button[type="submit"]')
                            if submit:
                                await submit.click()
                            await page.wait_for_timeout(10000)

                    await page.screenshot(path="screenshots/03_dashboard.png")

                    # Crawl dashboard - discover all links and buttons
                    print("[Crawl] Discovering page elements...")
                    links = await page.query_selector_all("a[href]")
                    buttons = await page.query_selector_all("button")

                    discovered_urls = []
                    for link in links:
                        href = await link.get_attribute("href")
                        if href:
                            discovered_urls.append(href)

                    discovered_buttons = []
                    for button in buttons:
                        text = await button.inner_text()
                        if text:
                            discovered_buttons.append(text.strip())

                    print(f"[Crawl] Found {{len(discovered_urls)}} links, {{len(discovered_buttons)}} buttons")

                    # Click each navigation link
                    for i, link in enumerate(links[:10]):  # Limit to first 10
                        try:
                            href = await link.get_attribute("href")
                            if href and not href.startswith("javascript:") and not href.startswith("#"):
                                print(f"[Crawl] Navigating to: {{href}}")
                                await link.click()
                                await page.wait_for_timeout(7000)
                                await page.screenshot(
                                    path=f"screenshots/{{i+4:02d}}_page.png"
                                )
                                await page.go_back()
                                await page.wait_for_timeout(5000)
                        except Exception as e:
                            print(f"[Crawl] Error clicking link: {{e}}")

                    # Final screenshot
                    await page.screenshot(path="screenshots/final_state.png")

                    await context.close()
                    await browser.close()

                    print("[Crawl] Done! Check screenshots/ directory for captures.")


            if __name__ == "__main__":
                asyncio.run(main())
        ''')
        return script
